"""SYNTHETIC TEST FIXTURES ONLY. These are generated arrays, not Sentinel-2 observations.

Layout mimics a Sentinel-2 L2A tile in UTM 43N near Pune: 10 m bands (B03, B04, B08) and 20 m bands (B11, SCL).
Left half of the scene = 'vegetation-like' reflectances, right half = 'built-up-like'. Content is constant inside
each 20 m block so that 10->20 m averaging is exact and expected index values can be computed by hand.
"""
import json
from pathlib import Path

import numpy as np
import rasterio
from rasterio.transform import from_origin
from rasterio.warp import transform_bounds

CRS = "EPSG:32643"
X0, Y0 = 378000.0, 2050000.0
N20 = 40  # 20 m pixels per side (800 m); 10 m grid is 80 x 80

# reflectances (veg half, urban half)
REFL = {"B03": (0.08, 0.12), "B04": (0.05, 0.15), "B08": (0.40, 0.20), "B11": (0.20, 0.30)}


def expected(index: str, half: int) -> float:
    r = {b: v[half] for b, v in REFL.items()}
    a, b = {"ndvi": ("B08", "B04"), "ndwi": ("B03", "B08"), "ndbi": ("B11", "B08")}[index]
    return (r[a] - r[b]) / (r[a] + r[b])


def scene_bbox_wgs84(shrink_m: float = 100.0) -> list[float]:
    """A lon/lat box fully inside the synthetic scene."""
    x1, y1 = X0 + N20 * 20, Y0 - N20 * 20
    return list(transform_bounds(CRS, "EPSG:4326", X0 + shrink_m, y1 + shrink_m, x1 - shrink_m, Y0 - shrink_m))


def _write(path: Path, arr: np.ndarray, res: float, nodata=0, crs=CRS, x0=X0, y0=Y0):
    with rasterio.open(path, "w", driver="GTiff", height=arr.shape[0], width=arr.shape[1], count=1, dtype=arr.dtype,
                       crs=crs, transform=from_origin(x0, y0, res, res), nodata=nodata) as d:
        d.write(arr, 1)


def make_scene(root: Path, name="S2X_SYNTH_20230115T050209", *, scale=1.0, offset=-1000, cloud_patch=True,
               with_scl=True, manifest=True, data_kind="synthetic_test_fixture", nodata_patch=False,
               omit: tuple[str, ...] = (), x0=X0, y0=Y0) -> Path:
    """Write a synthetic scene folder. `scale` multiplies NIR (to fake change between dates)."""
    d = root / name
    d.mkdir(parents=True, exist_ok=True)
    half20 = np.zeros((N20, N20), dtype=bool)
    half20[:, N20 // 2:] = True
    half10 = np.kron(half20, np.ones((2, 2), dtype=bool))

    def dn(band, half_mask):
        r = np.where(half_mask, REFL[band][1], REFL[band][0]).astype(np.float64)
        if band == "B08":
            r = r * scale
        return np.round(r * 10000 - offset).astype(np.uint16)  # DN = refl*10000 - offset

    bands = {"B03": (dn("B03", half10), 10), "B04": (dn("B04", half10), 10), "B08": (dn("B08", half10), 10),
             "B11": (dn("B11", half20), 20)}
    if nodata_patch:
        bands["B04"][0][40:44, 40:44] = 0  # DN 0 = nodata: a 4x4 block of 10 m pixels = 2x2 whole 20 m pixels, inside the region
    for b, (arr, res) in bands.items():
        if b not in omit:
            _write(d / f"{b}_{res}m.tif", arr, res, x0=x0, y0=y0)
    if with_scl and "SCL" not in omit:
        scl = np.full((N20, N20), 4, dtype=np.uint8)  # vegetation
        if cloud_patch:
            scl[:10, :10] = 9  # high-probability cloud: 100 px
        _write(d / "SCL_20m.tif", scl, 20, nodata=0, x0=x0, y0=y0)
    if manifest:
        (d / "scene.json").write_text(json.dumps({
            "acquisition_date": "-".join([name.split("_")[-1][:4], name.split("_")[-1][4:6], name.split("_")[-1][6:8]]),
            "boa_add_offset": offset, "data_kind": data_kind, "source": "SYNTHETIC TEST FIXTURE",
            "notes": "generated by tests; not a satellite observation"}))
    return d
